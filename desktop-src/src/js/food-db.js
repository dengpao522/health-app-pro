// 搜索索引：名字/全拼/别名/首字母 一次构建
const SEARCH_INDEX = FOOD_DB_EXTENDED.map(f => {
  const initial = (f.pinyin || '').replace(/[^a-z]/g, '').split('').reduce((acc, ch, i, arr) => {
    // 简化处理：直接提供全拼匹配 + 名字包含匹配已覆盖大部分场景
    return acc;
  }, '');
  return {
    ...f,
    haystacks: [
      f.name.toLowerCase(),
      (f.pinyin || '').toLowerCase(),
      ...(f.alias || []).map(a => a.toLowerCase()),
    ],
  };
});

/**
 * 搜索食物（名字包含 / 全拼包含 / 别名包含，置信度排序）
 * @param {string} kw 关键词
 * @param {number} limit 最多返回条数
 */
export function searchFood(kw, limit = 20) {
  const k = (kw || '').trim().toLowerCase();
  if (!k) return SEARCH_INDEX.slice(0, limit);
  const scored = [];
  for (const f of SEARCH_INDEX) {
    let score = 0;
    if (f.name === k) score = 100;
    else if (f.name.toLowerCase().startsWith(k)) score = 80;
    else if (f.name.toLowerCase().includes(k)) score = 60;
    else if ((f.pinyin || '').startsWith(k)) score = 50;
    else if ((f.alias || []).some(a => a === k)) score = 45;
    else if ((f.alias || []).some(a => a.includes(k))) score = 30;
    if (score > 0) scored.push({ f, score });
  }
  return scored.sort((a, b) => b.score - a.score).slice(0, limit).map(x => x.f);
}

/** 按分类取食物列表 */
export function foodsByCat(cat) {
  return FOOD_DB_EXTENDED.filter(f => f.cat === cat);
}

/** 转换为 scan 页搜索接口的返回格式 */
export function toSearchItem(f) {
  return {
    name: f.name, cat: f.cat, category: f.cat,
    calories: f.calories, protein: f.protein, fat: f.fat,
    carbs: f.carbs, fiber: f.fiber, sodium: f.sodium,
    serving_hint: '约 ' + f.unit,
  };
}
